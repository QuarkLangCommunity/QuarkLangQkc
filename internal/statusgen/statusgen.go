// Package statusgen renders the implementation-status report from machine-checkable claims.
//
// The standard's §11 used to be hand-written prose, and it drifted: this package derives the single
// status report from spec/status/claims.tsv, where every claim names the test or corpus case that pins
// it, and from spec/status/template.md, the prose that cannot be generated; §11 cites the report
// instead of repeating its tables. Evidence is resolved against the tree
// before anything is rendered, so a claim cannot cite a test that no longer exists and a corpus case
// cannot be silently left out.
package statusgen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	// DefaultClaims is the authored claims table, relative to the checkout root.
	DefaultClaims = "spec/status/claims.tsv"
	// DefaultTemplate is the authored prose template, relative to the checkout root.
	DefaultTemplate = "spec/status/template.md"
	// DefaultOut is the committed generated report, relative to the checkout root.
	DefaultOut    = "docs/implementation-status.md"
	generatedNote = "<!-- Generated by cmd/qkstatus from spec/status/claims.tsv and spec/status/template.md. Do not edit: run `go generate ./internal/statusgen`. -->\n"
)

// Options locates the inputs and chooses whether to write or to check the output.
type Options struct {
	Root     string // checkout root (default ".")
	Claims   string // claims table, relative to Root (default DefaultClaims)
	Template string // prose template, relative to Root (default DefaultTemplate)
	Out      string // generated report, relative to Root (default DefaultOut)
	Check    bool   // compare with Out instead of writing it
}

// claim is one row of the claims table: a construct, its status on each path, and the evidence.
type claim struct {
	section     string
	id          string
	construct   string
	checker     string
	interpreter string
	compiler    string
	evidence    []string
	note        string
}

// corpusCount is the number of parity cases the claims must cover.
type corpusCount struct {
	cases int
	run   int
}

// Run validates the claims and either writes the report or fails when it is stale.
func Run(opts Options) error {
	root := opts.Root
	if root == "" {
		root = "."
	}
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return fmt.Errorf("resolve root: %w", err)
	}
	claims, err := loadClaims(pathFor(absRoot, opts.Claims, DefaultClaims))
	if err != nil {
		return err
	}
	if err := validateClaims(absRoot, claims); err != nil {
		return err
	}
	if err := validateCorpusCoverage(absRoot, claims); err != nil {
		return err
	}
	corpus, err := corpusCountOf(absRoot)
	if err != nil {
		return err
	}
	tmplPath := pathFor(absRoot, opts.Template, DefaultTemplate)
	tmpl, err := os.ReadFile(tmplPath)
	if err != nil {
		return fmt.Errorf("read template: %w", err)
	}
	rendered, err := render(absRoot, claims, tmpl, corpus)
	if err != nil {
		return err
	}
	outPath := pathFor(absRoot, opts.Out, DefaultOut)
	if opts.Check {
		old, err := os.ReadFile(outPath)
		if err != nil {
			return fmt.Errorf("read %s: %w", display(absRoot, outPath), err)
		}
		want := strings.ReplaceAll(string(old), "\r\n", "\n")
		if want != string(rendered) {
			return fmt.Errorf("%s is out of date: run `go generate ./internal/statusgen`", display(absRoot, outPath))
		}
		return nil
	}
	if err := os.WriteFile(outPath, rendered, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", display(absRoot, outPath), err)
	}
	return nil
}

// pathFor resolves value against root, falling back to def when value is empty.
func pathFor(root, value, def string) string {
	if value == "" {
		value = def
	}
	if filepath.IsAbs(value) {
		return value
	}
	return filepath.Join(root, value)
}

// display renders a path relative to root when it is inside it, for stable error messages.
func display(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil || strings.HasPrefix(rel, "..") {
		return path
	}
	return filepath.ToSlash(rel)
}

// loadClaims parses the tab-separated claims table, skipping blank lines and # comments.
func loadClaims(path string) ([]claim, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read claims: %w", err)
	}
	var out []claim
	seen := map[string]bool{}
	sawHeader := false
	for i, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimRight(line, "\r")
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 8 {
			return nil, fmt.Errorf("%s:%d: want 8 tab-separated columns, got %d", filepath.Base(path), i+1, len(fields))
		}
		if !sawHeader {
			if fields[0] != "section" || fields[1] != "id" {
				return nil, fmt.Errorf("%s:%d: the first row must be the header", filepath.Base(path), i+1)
			}
			sawHeader = true
			continue
		}
		c := claim{
			section: fields[0], id: fields[1], construct: fields[2],
			checker: fields[3], interpreter: fields[4], compiler: fields[5],
			evidence: splitEvidence(fields[6]), note: fields[7],
		}
		if c.id == "" || seen[c.id] {
			return nil, fmt.Errorf("%s:%d: duplicate or empty id %q", filepath.Base(path), i+1, c.id)
		}
		seen[c.id] = true
		out = append(out, c)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no claims", filepath.Base(path))
	}
	if !sawHeader {
		return nil, fmt.Errorf("%s: no header row", filepath.Base(path))
	}
	return out, nil
}

// splitEvidence splits the semicolon-separated evidence column.
func splitEvidence(s string) []string {
	var out []string
	for _, part := range strings.Split(s, ";") {
		if part = strings.TrimSpace(part); part != "" {
			out = append(out, part)
		}
	}
	return out
}

// validateClaims checks every status and resolves every evidence reference.
func validateClaims(root string, claims []claim) error {
	for _, c := range claims {
		if err := validateStatus(c); err != nil {
			return err
		}
		if len(c.evidence) == 0 {
			return fmt.Errorf("%s: no evidence", c.id)
		}
	}
	return validateEvidence(root, claims)
}

// validateStatus checks the status values the two sections allow.
func validateStatus(c claim) error {
	ok := map[string]map[string]bool{
		"checker":     {"accept": true, "refuse": true},
		"interpreter": {"run": true, "refuse": true, "missing": true},
		"compiler":    {"lower": true, "partial": true, "refuse": true, "missing": true},
	}
	for name, value := range map[string]string{"checker": c.checker, "interpreter": c.interpreter, "compiler": c.compiler} {
		if !ok[name][value] {
			return fmt.Errorf("%s: invalid %s status %q", c.id, name, value)
		}
	}
	switch c.section {
	case "11.1":
		if c.checker != "accept" || c.interpreter != "run" || c.compiler != "lower" {
			return fmt.Errorf("%s: a §11.1 row must be accept/run/lower", c.id)
		}
	case "11.3":
		if c.note == "" {
			return fmt.Errorf("%s: a §11.3 row needs a note saying what the standard says", c.id)
		}
	default:
		return fmt.Errorf("%s: unknown section %q", c.id, c.section)
	}
	return nil
}

// validateEvidence resolves every reference, requiring a test and a corpus file for §11.1 rows.
func validateEvidence(root string, claims []claim) error {
	tests := map[string]map[string]bool{}
	for _, c := range claims {
		hasTest, hasInterp, hasCompiler := false, false, false
		for _, ref := range c.evidence {
			kind, ok := refKind(ref)
			if !ok {
				return fmt.Errorf("%s: evidence %q has no kind (test, file or glob)", c.id, ref)
			}
			switch kind {
			case "test":
				dir, name := splitTestRef(ref)
				if name == "" {
					return fmt.Errorf("%s: test evidence %q needs <dir>:<TestName>", c.id, ref)
				}
				if tests[dir] == nil {
					names, err := testNames(root, dir)
					if err != nil {
						return fmt.Errorf("%s: %w", c.id, err)
					}
					tests[dir] = names
				}
				if !tests[dir][name] {
					return fmt.Errorf("%s: %s has no test %s", c.id, dir, name)
				}
				hasTest = true
				if dir == "internal/lang" || strings.HasPrefix(dir, "internal/lang/") {
					hasInterp = true
				}
				if dir == "compiler" || strings.HasPrefix(dir, "compiler/") {
					hasCompiler = true
				}
			case "file":
				path := strings.TrimPrefix(ref, "file:")
				if err := requireFile(root, path); err != nil {
					return fmt.Errorf("%s: %w", c.id, err)
				}
				hasCompiler = true
				hasInterp = true
			case "glob":
				pattern := strings.TrimPrefix(ref, "glob:")
				matches, err := filepath.Glob(filepath.Join(root, filepath.FromSlash(pattern)))
				if err != nil || len(matches) == 0 {
					return fmt.Errorf("%s: glob %q matches no file", c.id, pattern)
				}
				hasCompiler = true
				hasInterp = true
			}
		}
		if c.section == "11.1" && (!hasTest || !hasInterp || !hasCompiler) {
			return fmt.Errorf("%s: a §11.1 row needs a test and evidence for both engines", c.id)
		}
	}
	return nil
}

// refKind returns the evidence kind before the first colon.
func refKind(ref string) (string, bool) {
	switch {
	case strings.HasPrefix(ref, "test:"):
		return "test", true
	case strings.HasPrefix(ref, "file:"):
		return "file", true
	case strings.HasPrefix(ref, "glob:"):
		return "glob", true
	}
	return "", false
}

// splitTestRef splits "<dir>:<TestName>" after the test: prefix.
func splitTestRef(ref string) (string, string) {
	rest := strings.TrimPrefix(ref, "test:")
	at := strings.LastIndex(rest, ":")
	if at < 0 {
		return rest, ""
	}
	return rest[:at], rest[at+1:]
}

// requireFile reports whether rel names an existing regular file under root.
func requireFile(root, rel string) error {
	info, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		return fmt.Errorf("evidence file %q: %w", rel, err)
	}
	if info.IsDir() {
		return fmt.Errorf("evidence file %q is a directory", rel)
	}
	return nil
}

// testNames parses the _test.go files in dir and returns the top-level test function names.
func testNames(root, dir string) (map[string]bool, error) {
	entries, err := os.ReadDir(filepath.Join(root, filepath.FromSlash(dir)))
	if err != nil {
		return nil, fmt.Errorf("read test package %s: %w", dir, err)
	}
	names := map[string]bool{}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		path := filepath.Join(root, filepath.FromSlash(dir), entry.Name())
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", path, err)
		}
		ast.Inspect(file, func(n ast.Node) bool {
			if fn, ok := n.(*ast.FuncDecl); ok && fn.Recv == nil {
				names[fn.Name.Name] = true
			}
			return true
		})
	}
	return names, nil
}

// validateCorpusCoverage fails when a parity case is not matched by any claim's evidence.
func validateCorpusCoverage(root string, claims []claim) error {
	for _, pattern := range []string{"compiler/testdata/cases/*.kq", "compiler/testdata/cases_run/*.kq"} {
		matches, err := filepath.Glob(filepath.Join(root, filepath.FromSlash(pattern)))
		if err != nil {
			return fmt.Errorf("glob %s: %w", pattern, err)
		}
		for _, path := range matches {
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			rel = filepath.ToSlash(rel)
			if !corpusCaseCovered(rel, claims) {
				return fmt.Errorf("corpus case %s is not matched by any claim's evidence: add it or widen the glob", rel)
			}
		}
	}
	return nil
}

// corpusCaseCovered reports whether one relative corpus path is matched by a file or glob reference.
func corpusCaseCovered(rel string, claims []claim) bool {
	for _, c := range claims {
		for _, ref := range c.evidence {
			switch {
			case strings.HasPrefix(ref, "file:") && strings.TrimPrefix(ref, "file:") == rel:
				return true
			case strings.HasPrefix(ref, "glob:"):
				if ok, _ := filepath.Match(strings.TrimPrefix(ref, "glob:"), rel); ok {
					return true
				}
			}
		}
	}
	return false
}

// corpusCountOf counts the parity cases the report covers.
func corpusCountOf(root string) (corpusCount, error) {
	var c corpusCount
	for _, group := range []struct {
		pattern string
		n       *int
	}{
		{"compiler/testdata/cases/*.kq", &c.cases},
		{"compiler/testdata/cases_run/*.kq", &c.run},
	} {
		matches, err := filepath.Glob(filepath.Join(root, filepath.FromSlash(group.pattern)))
		if err != nil {
			return c, fmt.Errorf("glob %s: %w", group.pattern, err)
		}
		*group.n = len(matches)
	}
	return c, nil
}

// render substitutes the generated tables and the corpus count into the authored template.
func render(root string, claims []claim, tmpl []byte, corpus corpusCount) ([]byte, error) {
	text := strings.ReplaceAll(string(tmpl), "\r\n", "\n")
	replacements := map[string]string{
		"{{table:11.1}}": renderBoth(root, claims, "11.1"),
		"{{table:11.3}}": renderDivergences(root, claims),
		"{{corpus}}":     corpusSentence(corpus),
	}
	for marker, value := range replacements {
		if !strings.Contains(text, marker) {
			return nil, fmt.Errorf("template has no %s", marker)
		}
		text = strings.ReplaceAll(text, marker, value)
	}
	if at := strings.Index(text, "{{"); at >= 0 {
		line := strings.Count(text[:at], "\n") + 1
		return nil, fmt.Errorf("template line %d has an unknown placeholder", line)
	}
	return []byte(generatedNote + "\n" + text), nil
}

// corpusSentence states the corpus counts the report covers.
func corpusSentence(c corpusCount) string {
	return fmt.Sprintf("The parity corpus has **%d** cases under `compiler/testdata/cases` and **%d** under `compiler/testdata/cases_run`; every one is matched by the evidence above. The two engines agree on all of them (`compare.sh`), which is why they can pin both paths at once.", c.cases, c.run)
}

// renderBoth renders the §11.1 table.
func renderBoth(root string, claims []claim, section string) string {
	var b strings.Builder
	b.WriteString("| Construct | Checker | Interpreter | Compiler | Evidence |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, c := range sorted(claims, section) {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n",
			cell(c.construct), label(c.checker), label(c.interpreter), label(c.compiler), evidenceCell(root, c.evidence))
	}
	return b.String()
}

// renderDivergences renders the §11.3 table.
func renderDivergences(root string, claims []claim) string {
	var b strings.Builder
	b.WriteString("| Construct | Checker | Interpreter | Compiler | Evidence | Note |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, c := range sorted(claims, "11.3") {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n",
			cell(c.construct), label(c.checker), label(c.interpreter), label(c.compiler),
			evidenceCell(root, c.evidence), cell(c.note))
	}
	return b.String()
}

// sorted returns the claims of one section in id order.
func sorted(claims []claim, section string) []claim {
	var out []claim
	for _, c := range claims {
		if c.section == section {
			out = append(out, c)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].id < out[j].id })
	return out
}

// label renders one status value for a table cell.
func label(status string) string {
	if text, ok := map[string]string{
		"accept": "accepts", "refuse": "refuses", "run": "runs",
		"lower": "lowers", "partial": "partly", "missing": "absent",
	}[status]; ok {
		return text
	}
	return status
}

// cell escapes a table cell's pipe characters.
func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// evidenceCell renders evidence references as inline code with glob counts.
func evidenceCell(root string, refs []string) string {
	parts := make([]string, 0, len(refs))
	for _, ref := range refs {
		parts = append(parts, evidenceText(root, ref))
	}
	return strings.Join(parts, "; ")
}

// evidenceText renders one evidence reference.
func evidenceText(root, ref string) string {
	kind, _ := refKind(ref)
	switch kind {
	case "test":
		dir, name := splitTestRef(ref)
		return "`" + dir + ":" + name + "`"
	case "file":
		return "`" + strings.TrimPrefix(ref, "file:") + "`"
	case "glob":
		pattern := strings.TrimPrefix(ref, "glob:")
		matches, _ := filepath.Glob(filepath.Join(root, filepath.FromSlash(pattern)))
		return fmt.Sprintf("`%s` (%d files)", pattern, len(matches))
	}
	return "`" + ref + "`"
}

