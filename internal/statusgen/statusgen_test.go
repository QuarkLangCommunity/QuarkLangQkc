package statusgen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestGeneratedStatusIsCurrent is the standing drift gate: the committed report must be exactly what the
// claims and template render, so a test, a corpus case or a claim edited without regenerating fails the
// ordinary go test run.
func TestGeneratedStatusIsCurrent(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	if err := Run(Options{Root: root, Check: true}); err != nil {
		t.Fatal(err)
	}
}

// TestStatusReportIsTheOnlyStatusCopy fails when the standard stops citing the report, when a second
// copy of the generated tables appears, or when another file claims to be generated by this package.
func TestStatusReportIsTheOnlyStatusCopy(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	standard := readFile(t, filepath.Join(root, "spec", "STANDARD.md"))
	section := between(t, standard, "## 11. Implementation status", "## 12. Change policy and revision log")
	if !strings.Contains(section, DefaultOut) {
		t.Errorf("spec/STANDARD.md §11 does not cite %s", DefaultOut)
	}
	if strings.Contains(section, "| Construct | Checker | Interpreter | Compiler |") {
		t.Errorf("spec/STANDARD.md §11 copies the status table instead of citing %s", DefaultOut)
	}
	err = filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == ".git" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".md") {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if rel == DefaultOut {
			return nil
		}
		text := readFile(t, path)
		if strings.Contains(text, "Generated by cmd/qkstatus") {
			t.Errorf("%s claims to be generated by cmd/qkstatus; %s is the single report", rel, DefaultOut)
		}
		if strings.Contains(text, "| Construct | Checker | Interpreter | Compiler |") {
			t.Errorf("%s carries a second implementation-status table; link %s instead", rel, DefaultOut)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

// readFile returns one file's contents with CRLF normalized.
func readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return strings.ReplaceAll(string(b), "\r\n", "\n")
}

// between returns the text between two markers, or fails when either is missing.
func between(t *testing.T, text, start, end string) string {
	t.Helper()
	i := strings.Index(text, start)
	j := strings.Index(text, end)
	if i < 0 || j < 0 || j <= i {
		t.Fatalf("missing section between %q and %q", start, end)
	}
	return text[i:j]
}
