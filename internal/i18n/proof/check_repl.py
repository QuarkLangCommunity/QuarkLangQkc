#!/usr/bin/env python3
"""P3's repl harness: the interactive session's own messages, rendered by both revisions.

`internal/lang/repl.go` is the one domain a process-level corpus cannot reach: the session echo comes
back through the session API, and the panic path needs a recovered panic. So this writes a tiny test
program that drives that API — the same entry point `qkrepl` uses, `NewREPLSession` + `Eval` — into each
revision's tree and builds it there, next to the package it tests, which is Go's rule for an internal
import. The two programs are run under QK_LANG=en and QK_LANG=zh and their output must be byte-identical,
the same claim as every other case in P3.

The program is written once and built twice, so it cannot encode this tree's behaviour in the baseline
side of the comparison.

Usage: check_repl.py <baseline-tree> <this-tree> <workdir>
"""
import os
import subprocess
import sys

PROGRAM = '''package lang

import (
	"fmt"
	"os"
	"testing"
)

// TestProofReplEcho prints the session echo for one declaration of each kind, in the language the
// environment selects. Generated by internal/i18n/proof/check_repl.py, built against two revisions.
func TestProofReplEcho(t *testing.T) {
	s, err := NewREPLSession(os.Stdin, os.Stdout)
	if err != nil {
		t.Fatal(err)
	}
	inputs := []string{
		"fn hello() int { return 1; }",
		"type struct { int x; } Point;",
		"type interface { fn area() int; } Shape;",
		"impl Point { fn area() int { return self.x; } }",
		"type int Meters;",
		"space demo { fn f() int { return 2; } }",
	}
	for _, in := range inputs {
		out, err := s.Eval(in)
		if err != nil {
			fmt.Println("ERR", err)
			continue
		}
		fmt.Print(out)
	}
	fmt.Println("-- done")
}
'''


def build(tree, work, label):
    path = os.path.join(tree, 'internal', 'lang', 'zz_replproof_test.go')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(PROGRAM)
    binary = os.path.join(work, 'bin', 'repl-%s.test' % label)
    r = subprocess.run(['go', 'test', '-c', '-o', binary, './internal/lang'], cwd=tree,
                       capture_output=True, text=True)
    os.unlink(path)
    if r.returncode != 0:
        print('building the repl harness in %s failed:\n%s' % (tree, r.stderr[-2000:]), file=sys.stderr)
        return None
    return binary


def run(binary, lang):
    r = subprocess.run([binary, '-test.run', 'TestProofReplEcho', '-test.v'], capture_output=True,
                       text=True, env=dict(os.environ, LANG='C.UTF-8', QK_LANG=lang))
    return r.stdout + r.stderr + 'rc=%d' % r.returncode


def main():
    base_tree, this_tree, work = sys.argv[1:4]
    os.makedirs(os.path.join(work, 'bin'), exist_ok=True)
    base = build(base_tree, work, 'baseline')
    proto = build(this_tree, work, 'prototype')
    if not base or not proto:
        return 1
    bad = 0
    for lang in ('en', 'zh'):
        a, b = run(base, lang), run(proto, lang)
        if a != b:
            bad += 1
            print('%s repl/echo DIFFERS' % lang, file=sys.stderr)
            al, bl = a.splitlines(), b.splitlines()
            for i in range(max(len(al), len(bl))):
                x = al[i] if i < len(al) else '<missing>'
                y = bl[i] if i < len(bl) else '<missing>'
                if x != y:
                    print('  line %d: %r -> %r' % (i + 1, x, y), file=sys.stderr)
        else:
            print('%-3s %-30s identical (%d bytes)' % (lang, 'repl/echo', len(a)))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
