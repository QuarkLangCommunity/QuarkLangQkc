// Package i18ngen turns the authored message tables under internal/i18n/source into the generated
// catalog: one stable Msg constant per message, and one contiguous byte blob plus an offset table.
//
// It is the build-time half of the i18n design (docs/i18n-design.md): the runtime reads an ID and
// slices the blob, so there is no map keyed by message text, no direction sniff and no fallback path
// to count. Completeness is checked here, before the code exists to compile, in both directions:
//
//   - every ID in the source has a value in every shipped language (a missing translation is a
//     missing column value and fails generation);
//   - every ID owned by the pinned qkparser module exists in that module at the version go.mod pins,
//     with exactly the source text this repository has written down for it.
//
// Nothing in this package is imported by the runtime.
package i18ngen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// Options locates the inputs and the output.
type Options struct {
	// SourceDir holds languages.tsv and the per-domain message tables (*.tsv).
	SourceDir string
	// OutFile is the generated file to write (or to compare against, with Check).
	OutFile string
	// ModuleDir is the checked-out source directory of the pinned qkparser module, or "" when it
	// could not be located; then imported IDs are reported instead of checked.
	ModuleDir string
	// ModuleSource is the module's authored table, relative to ModuleDir.
	ModuleSource string
	// Package is the package clause of the generated file.
	Package string
	// Header names the generator and the command that reproduces the file.
	Header string
	// Check compares the generated bytes with OutFile instead of writing them.
	Check bool
}

// DefaultModuleSource is where the pinned module keeps its authored table.
const DefaultModuleSource = "i18n/source/messages.tsv"

// Language is one shipped language, in file order.
type Language struct {
	Code      string // "en"
	Direction string // "source" or "translation"
}

// Message is one authored message: its ID, the owner of its text, what that owner ships today, and
// one rendering per shipped language.
type Message struct {
	ID      string
	Owner   string
	Context string
	Note    string
	// Source is the text the owning module ships for this ID today. For an imported ID it is checked
	// against the pinned module; for a local ID it repeats the source language's value.
	Source string
	Values []string // parallel to the language list; the first is the source language
}

// Table is the whole authored input.
type Table struct {
	Languages []Language
	Messages  []Message
}

// Sources bundles everything generation reads, so a test can drive it without touching disk.
type Sources struct {
	Table     Table
	ModuleRaw []byte // the pinned module's authored table, or nil when it is unavailable
}

// ParseLanguages reads languages.tsv: one <lang, dir> row per shipped language, in index order.
func ParseLanguages(name string, raw []byte) ([]Language, error) {
	var out []Language
	err := parseRows(name, raw, 2, func(line int, fields []string) error {
		if fields[1] != "source" && fields[1] != "translation" {
			return fmt.Errorf("%s:%d: direction %q is neither source nor translation", name, line, fields[1])
		}
		out = append(out, Language{Code: fields[0], Direction: fields[1]})
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no languages", name)
	}
	sources := 0
	for _, l := range out {
		if l.Direction == "source" {
			sources++
		}
	}
	if sources != 1 {
		return nil, fmt.Errorf("%s: exactly one language must be the source, got %d", name, sources)
	}
	if out[0].Direction != "source" {
		return nil, fmt.Errorf("%s: the source language must come first (the blob's first block is the source), got %q", name, out[0].Code)
	}
	for i := 1; i < len(out); i++ {
		if out[i].Code == out[i-1].Code {
			return nil, fmt.Errorf("%s: language %q is listed twice", name, out[i].Code)
		}
	}
	return out, nil
}

// ParseMessages reads one domain table: id, owner, ctx, note, src, then one value column per language.
func ParseMessages(name string, raw []byte, langs []Language) ([]Message, error) {
	want := 5 + len(langs)
	var out []Message
	err := parseRows(name, raw, want, func(line int, fields []string) error {
		if fields[1] != "local" && fields[1] != "import" {
			return fmt.Errorf("%s:%d: owner %q is neither local nor import", name, line, fields[1])
		}
		if !idRe.MatchString(fields[0]) {
			return fmt.Errorf("%s:%d: id %q is not <domain>.<snake_case>", name, line, fields[0])
		}
		if fields[1] == "local" && strings.TrimSpace(fields[4]) != strings.TrimSpace(fields[5]) {
			return fmt.Errorf("%s:%d: a local id's src must be its source-language value, got %s vs %s", name, line, fields[4], fields[5])
		}
		src, serr := strconv.Unquote(strings.TrimSpace(fields[4]))
		if serr != nil {
			return fmt.Errorf("%s:%d: src is not a quoted Go string: %v", name, line, serr)
		}
		if src == "" {
			return fmt.Errorf("%s:%d: %s has an empty src value", name, line, fields[0])
		}
		m := Message{ID: fields[0], Owner: fields[1], Context: fields[2], Note: fields[3], Source: src}
		for k := range langs {
			text, uerr := strconv.Unquote(strings.TrimSpace(fields[5+k]))
			if uerr != nil {
				return fmt.Errorf("%s:%d: value for %s is not a quoted Go string: %v", name, line, langs[k].Code, uerr)
			}
			if text == "" {
				return fmt.Errorf("%s:%d: %s has an empty %s value", name, line, fields[0], langs[k].Code)
			}
			m.Values = append(m.Values, text)
		}
		out = append(out, m)
		return nil
	})
	return out, err
}

// ParseModuleTable reads the pinned module's own table, which is id, lang, text: the module owns the
// source text of its messages and nothing else, so it has no owner/context/note columns and exactly
// one authored language. Two columns are synthesised here so both tables parse through one code path.
func ParseModuleTable(name string, raw []byte) ([]Message, error) {
	var out []Message
	err := parseRows(name, raw, 3, func(line int, fields []string) error {
		if !idRe.MatchString(fields[0]) {
			return fmt.Errorf("%s:%d: id %q is not <domain>.<snake_case>", name, line, fields[0])
		}
		text, uerr := strconv.Unquote(strings.TrimSpace(fields[2]))
		if uerr != nil {
			return fmt.Errorf("%s:%d: text is not a quoted Go string: %v", name, line, uerr)
		}
		out = append(out, Message{ID: fields[0], Owner: "import", Context: "module", Note: fields[1], Source: text, Values: []string{text}})
		return nil
	})
	return out, err
}

var idRe = regexp.MustCompile(`^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$`)

// parseRows walks the data lines of a table, handing each row's columns to fn. The last column is the
// message text and absorbs any tab inside it, so a template may contain a tab without shifting the
// columns; a row that lost a language column still fails, because the count is exact.
func parseRows(name string, raw []byte, want int, fn func(line int, fields []string) error) error {
	for _, row := range splitTable(raw) {
		line, text := row.Line, row.Text
		fields := strings.SplitN(text, "\t", want)
		if len(fields) != want {
			return fmt.Errorf("%s:%d: want %d tab-separated columns, got %d (a missing language is a missing column)", name, line, want, len(fields))
		}
		for i := range fields {
			fields[i] = strings.TrimSpace(fields[i])
		}
		if err := fn(line, fields); err != nil {
			return err
		}
	}
	return nil
}

// Row is one data line of a table, with the line number it came from so a diagnostic can point at it.
type Row struct {
	Line int
	Text string
}

// splitTable drops blank lines and comments and returns the rest in file order. The order is load
// bearing: a message's number is its position in the table, so walking a map here would renumber the
// whole blob on every run.
func splitTable(raw []byte) []Row {
	var out []Row
	for i, line := range strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "#") {
			continue
		}
		out = append(out, Row{Line: i + 1, Text: line})
	}
	return out
}

// Load reads the authored tables from disk and, when ModuleDir is set, the pinned module's table too.
func Load(opts Options) (*Sources, error) {
	langRaw, err := os.ReadFile(filepath.Join(opts.SourceDir, "languages.tsv"))
	if err != nil {
		return nil, err
	}
	langs, err := ParseLanguages("languages.tsv", langRaw)
	if err != nil {
		return nil, err
	}
	order, err := readTableOrder(opts.SourceDir)
	if err != nil {
		return nil, err
	}
	var msgs []Message
	for _, name := range order {
		raw, rerr := os.ReadFile(filepath.Join(opts.SourceDir, name))
		if rerr != nil {
			return nil, rerr
		}
		part, perr := ParseMessages(name, raw, langs)
		if perr != nil {
			return nil, perr
		}
		msgs = append(msgs, part...)
	}
	src := &Sources{Table: Table{Languages: langs, Messages: msgs}}
	if opts.ModuleDir != "" {
		raw, rerr := os.ReadFile(filepath.Join(opts.ModuleDir, opts.ModuleSource))
		if rerr != nil {
			return nil, fmt.Errorf("the pinned module's table: %w", rerr)
		}
		src.ModuleRaw = raw
	}
	return src, nil
}

// readTableOrder reads tables.tsv: the message tables in load order, one file name per line.
//
// The order used to be the alphabetical order of source/*.tsv, which was wrong in a way nothing would
// have caught until it mattered: a message's number is its position in the concatenated tables, and
// internal/lang answers a qkparser.ID by converting it straight to a Msg. The module's IDs are
// positions in the module's own table, so the tables this repository imports must come first, in the
// module's order. A table named docgen.tsv sorts before parser.tsv, so adding one domain under the old
// rule renumbered all 63 syntax-layer messages and the conversion silently started meaning different
// messages on the two sides of the seam.
//
// It is a list rather than a rule because a rule that has to be inferred from file names is exactly how
// this broke. Every *.tsv that is neither languages.tsv nor tables.tsv must appear here, so a table
// cannot be added and silently ignored.
func readTableOrder(dir string) ([]string, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "tables.tsv"))
	if err != nil {
		return nil, fmt.Errorf("source/tables.tsv (the load order of the message tables): %w", err)
	}
	var order []string
	seen := map[string]bool{}
	err = parseRows("tables.tsv", raw, 1, func(line int, fields []string) error {
		name := fields[0]
		if !strings.HasSuffix(name, ".tsv") || strings.ContainsAny(name, `/\`) {
			return fmt.Errorf("tables.tsv:%d: %q is not a table file name", line, name)
		}
		if name == "tables.tsv" || name == "languages.tsv" {
			return fmt.Errorf("tables.tsv:%d: %s is read by the generator, not a message table", line, name)
		}
		if seen[name] {
			return fmt.Errorf("tables.tsv:%d: %s is listed twice", line, name)
		}
		seen[name] = true
		order = append(order, name)
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(order) == 0 {
		return nil, fmt.Errorf("tables.tsv: no message tables listed")
	}
	present, gerr := filepath.Glob(filepath.Join(dir, "*.tsv"))
	if gerr != nil {
		return nil, gerr
	}
	for _, path := range present {
		base := filepath.Base(path)
		if (base == "tables.tsv" || base == "languages.tsv") || seen[base] {
			continue
		}
		return nil, fmt.Errorf("source/%s is not listed in tables.tsv, so generation would ignore it", base)
	}
	return order, nil
}

// Complete reports every message that has no value in a shipped language. It cannot happen through
// ParseMessages — a missing value is a missing column and the row does not parse — so this is the
// check that also guards a Sources built by hand.
func (s *Sources) Complete() []string {
	var missing []string
	for _, m := range s.Table.Messages {
		if len(m.Values) != len(s.Table.Languages) {
			missing = append(missing, fmt.Sprintf("%s: %d values for %d languages", m.ID, len(m.Values), len(s.Table.Languages)))
			continue
		}
		if strings.TrimSpace(m.Source) == "" {
			missing = append(missing, fmt.Sprintf("%s: no src value", m.ID))
		}
		for i, v := range m.Values {
			if strings.TrimSpace(v) == "" {
				missing = append(missing, fmt.Sprintf("%s: no %s value", m.ID, s.Table.Languages[i].Code))
			}
		}
	}
	return missing
}

// CheckModule verifies this repository against the pinned module, in both directions:
//
//   - every ID the module ships must be carried here, with a value in every shipped language. This is
//     the direction that closes the hole: a message added to the syntax layer is an ID this repository
//     has never seen, so it fails here instead of rendering untranslated in a user's terminal.
//   - every imported row must still match the module's text, so a rephrasing there is a failure here
//     rather than a translation silently attached to wording that no longer exists.
func (s *Sources) CheckModule() []string {
	if s.ModuleRaw == nil {
		var out []string
		for _, m := range s.Table.Messages {
			if m.Owner == "import" {
				out = append(out, m.ID)
			}
		}
		if len(out) > 0 {
			return []string{fmt.Sprintf("the pinned module's table is unavailable, so %d imported ids are unchecked: %s", len(out), strings.Join(out, ", "))}
		}
		return nil
	}
	modMsgs, err := ParseModuleTable("module messages.tsv", s.ModuleRaw)
	if err != nil {
		return []string{err.Error()}
	}
	byID := map[string]Message{}
	for _, m := range modMsgs {
		byID[m.ID] = m
	}
	claimed := map[string]bool{}
	var problems []string
	for _, m := range s.Table.Messages {
		if m.Owner != "import" {
			continue
		}
		claimed[m.ID] = true
		mod, ok := byID[m.ID]
		if !ok {
			problems = append(problems, fmt.Sprintf("%s: this repository carries the id but the pinned module does not ship it", m.ID))
			continue
		}
		if mod.Source != m.Source {
			problems = append(problems, fmt.Sprintf("%s: this repository records src %q but the pinned module ships %q", m.ID, m.Source, mod.Source))
		}
	}
	// The module's own order, so the report reads in the order a reader can check against the module.
	for _, mod := range modMsgs {
		if !claimed[mod.ID] {
			problems = append(problems, fmt.Sprintf("%s: the pinned module ships this message and no row in this catalog carries it (its text is %q)", mod.ID, mod.Source))
		}
	}
	return problems
}

// constName turns "parser.nesting_too_deep" into "MsgParserNestingTooDeep".
func constName(id string) string {
	parts := strings.Split(id, ".")
	var b strings.Builder
	b.WriteString("Msg")
	for _, p := range parts {
		for _, w := range strings.Split(p, "_") {
			if w == "" {
				continue
			}
			b.WriteString(strings.ToUpper(w[:1]))
			b.WriteString(w[1:])
		}
	}
	return b.String()
}

// quote renders a Go string literal, preferring a raw literal so the blob stays readable in review.
func quote(s string) string {
	if !strings.ContainsAny(s, "`\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// Generate renders the generated catalog file. Message numbers are the position of the ID in the
// table, and the table is append-only by convention, so a number never changes meaning.
func Generate(s *Sources) ([]byte, error) {
	if len(s.Table.Messages) == 0 {
		return nil, fmt.Errorf("no messages")
	}
	if len(s.Table.Languages) == 0 {
		return nil, fmt.Errorf("no languages")
	}
	seen := map[string]bool{}
	for _, m := range s.Table.Messages {
		if seen[m.ID] {
			return nil, fmt.Errorf("duplicate id %s", m.ID)
		}
		seen[m.ID] = true
	}
	nLangs, nMsgs := len(s.Table.Languages), len(s.Table.Messages)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by %s from %s. DO NOT EDIT.\n", "cmd/qki18n", "internal/i18n/source/*.tsv")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// A message's identity is its Msg constant, never its text, so rephrasing a message cannot change\n")
	fmt.Fprintf(&b, "// which message it is. The text of every message in every shipped language is one contiguous blob\n")
	fmt.Fprintf(&b, "// (msgBlob) addressed through msgOffsets: rendering is an index and a slice, not a map lookup.\n")
	fmt.Fprintf(&b, "\npackage %s\n\n", "i18n")
	fmt.Fprintf(&b, "// Msg identifies one message. It is stable: never renumber, never recycle.\n")
	fmt.Fprintf(&b, "type Msg uint16\n\n")
	fmt.Fprintf(&b, "// Message constants, in table order.\nconst (\n")
	for i, m := range s.Table.Messages {
		fmt.Fprintf(&b, "\t%s Msg = %d\n", constName(m.ID), i)
	}
	fmt.Fprintf(&b, ")\n\n")

	fmt.Fprintf(&b, "// msgLangs are the shipped languages, in blob-block order. The first is the source language.\n")
	fmt.Fprintf(&b, "var msgLangs = [...]string{")
	for i, l := range s.Table.Languages {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", l.Code)
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// msgOffsets has one entry per (language, message) pair plus a final sentinel: the pair at flat\n")
	fmt.Fprintf(&b, "// index lang*%d+id occupies msgBlob[msgOffsets[k]:msgOffsets[k+1]].\n", nMsgs)
	fmt.Fprintf(&b, "var msgOffsets = [...]uint32{\n")
	total := 0
	fmt.Fprintf(&b, "\t%d,\n", total)
	for li := range s.Table.Languages {
		for mi := range s.Table.Messages {
			total += len(s.Table.Messages[mi].Values[li])
			fmt.Fprintf(&b, "\t%d,\n", total)
		}
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// msgBlob is every message in every language, back to back, in language-then-table order.\n")
	fmt.Fprintf(&b, "const msgBlob = %s\n\n", quote(blob(s)))

	fmt.Fprintf(&b, "// msgText returns the value of a message in one language block, read out of the blob. One index\n")
	fmt.Fprintf(&b, "// computation and one slice: no map, no hash of the message text, no fallback branch.\n")
	fmt.Fprintf(&b, "func msgText(id Msg, block int) string {\n")
	fmt.Fprintf(&b, "\tif block < 0 || block >= %d || int(id) >= %d {\n", nLangs, nMsgs)
	fmt.Fprintf(&b, "\t\treturn \"\"\n\t}\n")
	fmt.Fprintf(&b, "\tk := block*%d + int(id)\n", nMsgs)
	fmt.Fprintf(&b, "\treturn msgBlob[msgOffsets[k]:msgOffsets[k+1]]\n}\n\n")

	fmt.Fprintf(&b, "// MsgLangs returns the shipped languages, in blob order (the source language first).\n")
	fmt.Fprintf(&b, "func MsgLangs() []string { return append([]string(nil), msgLangs[:]...) }\n\n")

	fmt.Fprintf(&b, "// MsgKey returns the dotted id of a message, for diagnostics and test names.\n")
	fmt.Fprintf(&b, "func MsgKey(id Msg) string {\n\tkeys := MsgKeys()\n\tif int(id) >= len(keys) {\n\t\treturn \"\"\n\t}\n\treturn keys[id]\n}\n\n")
	fmt.Fprintf(&b, "// MsgKeys returns every message id, in table order, for diagnostics and ratchets.\n")
	fmt.Fprintf(&b, "func MsgKeys() []string {\n\treturn []string{\n")
	for _, m := range s.Table.Messages {
		fmt.Fprintf(&b, "\t\t%q,\n", m.ID)
	}
	fmt.Fprintf(&b, "\t}\n}\n\n")

	fmt.Fprintf(&b, "// langBlock maps a language code to its blob block; an unknown language renders the source.\n")
	fmt.Fprintf(&b, "func langBlock(code string) int {\n\tfor i, l := range msgLangs {\n\t\tif l == code {\n\t\t\treturn i\n\t\t}\n\t}\n\treturn 0\n}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated source does not compile: %w", err)
	}
	return formatted, nil
}

// blob concatenates every value in language-then-table order; the offset table carries the
// boundaries, so no separator is needed and a message may contain any byte.
func blob(s *Sources) string {
	var b strings.Builder
	for li := range s.Table.Languages {
		for mi := range s.Table.Messages {
			b.WriteString(s.Table.Messages[mi].Values[li])
		}
	}
	return b.String()
}

// Run generates (or checks) the file, returning every problem it found. A non-empty result is a build
// failure: the caller must not accept a catalog with a message that has no value in a shipped
// language, or an imported id the pinned module does not ship.
func Run(opts Options) []string {
	src, err := Load(opts)
	if err != nil {
		return []string{err.Error()}
	}
	var problems []string
	problems = append(problems, src.Complete()...)
	problems = append(problems, src.CheckModule()...)
	if len(problems) > 0 {
		return problems
	}
	out, err := Generate(src)
	if err != nil {
		return []string{err.Error()}
	}
	if opts.Check {
		got, rerr := os.ReadFile(opts.OutFile)
		if rerr != nil {
			return []string{rerr.Error()}
		}
		if !bytes.Equal(normalizeEOL(got), normalizeEOL(out)) {
			return []string{fmt.Sprintf("%s is out of date: regenerate it with `go generate ./internal/i18n`", opts.OutFile)}
		}
		return nil
	}
	if err := os.WriteFile(opts.OutFile, out, 0o644); err != nil {
		return []string{err.Error()}
	}
	return nil
}

// ---- in-memory access, so a proof can mutate an authored table without touching disk ----

// Clone deep-copies a Sources so a proof can mutate one copy without affecting the next.
func (s *Sources) Clone() *Sources {
	out := &Sources{ModuleRaw: append([]byte(nil), s.ModuleRaw...)}
	out.Table.Languages = append([]Language(nil), s.Table.Languages...)
	for _, m := range s.Table.Messages {
		c := m
		c.Values = append([]string(nil), m.Values...)
		out.Table.Messages = append(out.Table.Messages, c)
	}
	return out
}

// index returns the position of an id, or -1.
func (s *Sources) index(id string) int {
	for i, m := range s.Table.Messages {
		if m.ID == id {
			return i
		}
	}
	return -1
}

// langIndex returns the position of a language code, or -1.
func (s *Sources) langIndex(code string) int {
	for i, l := range s.Table.Languages {
		if l.Code == code {
			return i
		}
	}
	return -1
}

// Value returns a message's value in one language, or "" when either is unknown. The proofs use it
// to state their premise (what the authored English is) before they perturb it.
func (s *Sources) Value(id, lang string) string {
	mi, li := s.index(id), s.langIndex(lang)
	if mi < 0 || li < 0 || li >= len(s.Table.Messages[mi].Values) {
		return ""
	}
	return s.Table.Messages[mi].Values[li]
}

// SetValue overwrites a message's value in one language, and keeps src in step for the source
// language so a local message does not start failing its own consistency check.
func (s *Sources) SetValue(id, lang, text string) bool {
	mi, li := s.index(id), s.langIndex(lang)
	if mi < 0 || li < 0 || li >= len(s.Table.Messages[mi].Values) {
		return false
	}
	s.Table.Messages[mi].Values[li] = text
	if li == 0 && s.Table.Messages[mi].Owner == "local" {
		s.Table.Messages[mi].Source = text
	}
	return true
}

// SetSource overwrites the text recorded as the owning module's, which is what a drift check reads.
func (s *Sources) SetSource(id, text string) bool {
	mi := s.index(id)
	if mi < 0 {
		return false
	}
	s.Table.Messages[mi].Source = text
	return true
}

// DropValue removes a message's value in one language, which also removes the column: the value list
// is one shorter, exactly as a table row that lost a column would parse.
func (s *Sources) DropValue(id, lang string) bool {
	mi, li := s.index(id), s.langIndex(lang)
	if mi < 0 || li < 0 || li >= len(s.Table.Messages[mi].Values) {
		return false
	}
	m := &s.Table.Messages[mi]
	m.Values = append(append([]string(nil), m.Values[:li]...), m.Values[li+1:]...)
	return true
}

// RunWith is Run for an in-memory table: it checks completeness and the module's IDs, then writes (or
// compares) the generated file. Nothing is read from the source directory.
func RunWith(opts Options, src *Sources) []string {
	var problems []string
	problems = append(problems, src.Complete()...)
	problems = append(problems, src.CheckModule()...)
	if len(problems) > 0 {
		return problems
	}
	out, err := Generate(src)
	if err != nil {
		return []string{err.Error()}
	}
	if opts.Check {
		got, rerr := os.ReadFile(opts.OutFile)
		if rerr != nil {
			return []string{rerr.Error()}
		}
		if !bytes.Equal(normalizeEOL(got), normalizeEOL(out)) {
			return []string{fmt.Sprintf("%s is out of date: regenerate it with `go generate ./internal/i18n`", opts.OutFile)}
		}
		return nil
	}
	if err := os.WriteFile(opts.OutFile, out, 0o644); err != nil {
		return []string{err.Error()}
	}
	return nil
}

// normalizeEOL folds CRLF to LF, so a content check is not decided by how a platform checked a file
// out: the generated content is the contract, the checkout's line endings are not.
func normalizeEOL(b []byte) []byte { return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")) }
